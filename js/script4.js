let dia = prompt("Digite o dia da semana sendo 1-domingo e 7-sábado");
if(dia ==1){
    alert("Hoje é domingo");
}else if (dia == 2){
    alert("Hoje é segunda");
}else if (dia == 3){
    alert("Hoje é terça");
}else if (dia == 4){
    alert("Hoje é quarta");
}else if (dia == 5){
    alert("Hoje é quinta");
}else if (dia == 6){
    alert("Hoje é sexta");
}else if (dia == 7){
    alert("Hoje é sábado");
}else{
    alert("Dia inválido")
}